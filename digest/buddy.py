# Присказка в начале: «блин, …», «ну вот, …», «да блин, это жесть: …», «ну охуеть, …». Одна такая на выпуск — живая
# реакция, в каждой карточке — та же болезнь, что «Значит,» в «почему важно»: на настоящих карточках Haiku ставила её
# в четырёх из семи (eval 19.11.2026). Присказка — до трёх слов-междометий перед первым знаком, без единого факта
# Начинается она с настоящего междометия: «всё, что известно: …» и «это-то понятно» — обычные фразы
_STARTS = (r"(?:ну|да|вот|ого|ой|ох|блин|бля|блять|блядь|слушай|короче|ахах\w*|ахренеть|охренеть|охуеть|ебать"
           r"|пиздец|жесть)")
_FILLER = rf"(?:{_STARTS}|это|и|всё|уже|такое|серь[её]зно|хрень)"
_CLAUSE = rf"(?:\s+{_FILLER}){{0,3}}\s*[,.:!—]+\s*"
OPENER = re.compile(rf"^{_STARTS}{_CLAUSE}(?:(?:это|ну|вот){_CLAUSE})*", re.I)
# «вывод: …» — подпись из подачи карточки модели («… Вывод: …»), читателю она ни к чему
LABEL = re.compile(r"(?<!\w)вывод:\s*", re.I)
ATTEMPTS = 2
MAT = re.compile(r"пизд|ху[йеяё]|еба|ёб|бля|нахуй|охуе|заеб", re.I)
# Сумма со сленговой единицей: «6,34 ляма» вместо «6,34 млрд» проверка чисел не видит — число то же
SLANG_SUM = re.compile(r"\d[\d.,]*\s*(?:лям|лярд|косар)", re.I)
SCALED = re.compile(r"(\d[\d.,]*)\s*(трлн|триллион|млрд|миллиард|млн|миллион|тыс)", re.I)
SCALE_OF = {"тр": "трлн", "млр": "млрд", "миллиа": "млрд", "млн": "млн", "миллио": "млн", "ты": "тыс"}
LATIN = re.compile(r"[A-Za-z][A-Za-z0-9]*(?:[.+#-][A-Za-z0-9]+)*")
# Пересказы выходят короче карточки (0,6–1,0 её длины); заметно длиннее — значит, модель дописала своё,
# втрое короче — от карточки осталась одна реакция («ну пиздец.»)
MAX_GROWTH = 1.25
MIN_SHARE = 0.35
# Модель вышла из роли и обсуждает саму заметку: «Заметка такая: …», «твой вывод из заметки не следует»
OUT_OF_ROLE = re.compile(r"заметк|твой вывод|вывод (?:из|про|верный)", re.I)


def _scaled(text: str) -> set[tuple[str, str]]:
    """Пары «число — порядок»: 6,34 млрд и 6,34 млн — разные суммы, хотя число одно."""
    return {(number.replace(".", ","), next(scale for prefix, scale in SCALE_OF.items() if unit.lower().startswith(prefix)))
            for number, unit in SCALED.findall(text)}


def faithful(said: str, sober: str, source: str) -> str:
    """Пустая строка — пересказ не расходится с карточкой; иначе причина, по которой он не годится."""
    if not said:
        return "пустой ответ"
    if len(said) > MAX_GROWTH * len(sober):
        return "длиннее карточки"
    if len(said) < MIN_SHARE * len(sober):
        return "от карточки осталась одна реакция"
    if OUT_OF_ROLE.search(said):
        return "обсуждает заметку вместо пересказа"
    if SLANG_SUM.search(said):
        return "сумма со сленговой единицей"
    lost = invented_numbers(sober, said)
    if lost:
        return f"потеряны числа {lost}"
    if not _scaled(sober) <= _scaled(said):
        return "у суммы сменился порядок"
    known = f"{sober} {source}"
    if not _scaled(said) <= _scaled(known):
        return "у суммы появился порядок, которого нет в карточке"
    extra = invented_numbers(said, known)
    if extra:
        return f"числа не из карточки {extra}"
    haystack = known.lower()
    names = sorted({w for w in LATIN.findall(said) if len(w) > 2 and w.lower() not in haystack})
    return f"названия не из карточки {names}" if names else ""


def retell(entries: list[Entry], texts: dict[str, str], records: dict[str, str], models: list[str]) -> None:
    """Пересказывает карточки событий и голосов платной моделью; вывод «почему важно» уходит внутрь рассказа.
    Фишки не трогаем: в них точные названия файлов и настроек, по которым читатель действует. Модели нет или она
    отказала — карточки остаются прежними: голос — надстройка, выпуск выходит и без него."""
    if not models:
        return
    opened = False
    for n, entry in enumerate(entries):
        if entry.section == "tips":
            continue
        # С заголовком: пересказ карточки часто начинается с «Модель нужна, чтобы…», и без него теряется, о чём речь
        sober = f"{entry.title}. {entry.summary} Вывод: {entry.why or '—'}"
        source = known_text(entry.item, texts, records)
        # Вторая попытка — с другим порядком примеров: в тестовом выпуске 19.11.2026 без неё половина карточек
        # осталась сухой, и выпуск вышел пёстрым
        for attempt in range(ATTEMPTS):
            examples = EXAMPLES[:]
            # Свой порядок примеров у каждой карточки: при одном порядке модель повторяет начало последнего примера
            random.Random(n + attempt * len(entries)).shuffle(examples)
            history: list[MessageParam] = []
            for dry, said in examples:
                history += [{"role": "user", "content": dry}, {"role": "assistant", "content": said}]
            history.append({"role": "user", "content": sober})
            try:
                said = LABEL.sub("", llm.say(SYSTEM, history, models[0], call="buddy").strip())
            except LlmError as exc:
                log.error("пересказ голосом недоступен, остальные карточки остаются как есть: %s", exc)
                return
            if opened:
                said = OPENER.sub("", said)
            # Проверяем то, что пойдёт в выпуск: без присказки от ответа может не остаться ничего
            reason = faithful(said, sober, source)
            if not reason:
                opened = opened or bool(OPENER.match(said))
                entry.summary, entry.why = said, ""
                break
            log.warning("пересказ голосом отброшен (%s), попытка %d: %s", reason, attempt + 1, entry.title)
