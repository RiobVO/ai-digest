def cap_section(digest: Digest, section: str, limit: int) -> None:
    """Не больше limit карточек раздела: остальные — строкой в начало «Ещё за день». Модель правило из промпта не
    держит (23.10: 6 событий безопасности из 13 при «2–4»), а читателю нужны и ИИ, и технологии. Записи уже
    по важности, поэтому остаются самые важные."""
    kept: list[Entry] = []
    moved: list[Entry] = []
    for entry in digest.entries:
        (moved if entry.section == section and sum(e.section == section for e in kept) >= limit else kept).append(entry)
    digest.entries = kept
    digest.more[:0] = [Mention(e.item, e.title) for e in moved]


def cap_events(digest: Digest, limit: int) -> None:
    """Не больше limit событий дня: остальные — строкой в начало «Ещё за день». Голоса и фишки идут сверх событий
    и в счёт не входят. Число карточек из промпта Lite не держит так же, как лимит раздела (см. cap_section).
    Записи уже по важности, поэтому остаются самые важные."""
    events = [e for e in digest.entries if e.section not in EXTRA_SECTIONS]
    # По объекту, а не по равенству: две карточки с одинаковыми полями — всё равно разные записи
    moved = {id(e) for e in events[limit:]}
    digest.entries = [e for e in digest.entries if id(e) not in moved]
    digest.more[:0] = [Mention(e.item, e.title) for e in events[limit:]]


# «Главное за день» по шкале промпта — важность от 8, у одного-трёх событий в обычный день. Lite шкалу не держит:
# в выпусках с отбором на Lite ≥8 получали 59% карточек против 24% у 3.8 Flash (28 выпусков до 05.11.2026), и метка
# «горячо» на странице теряла смысл. Порядок карточек модель уже задала, поэтому лишним только снижаем оценку
HOT_IMPORTANCE = 8


def cap_hot(digest: Digest, limit: int) -> None:
    """Важность ≥HOT_IMPORTANCE остаётся не больше чем у limit первых карточек; у остальных она опускается под порог."""
    hot = 0
    for entry in digest.entries:
        if entry.importance < HOT_IMPORTANCE:
            continue
        hot += 1
        if hot > limit:
            entry.importance = HOT_IMPORTANCE - 0.1


def entry_rank(entry: Entry) -> tuple[bool, float]:
    """Порядок записей выпуска: авторский пост и лайфхак — не новость дня и идут после событий,
    иначе мнение или приём стали бы «Главным»."""
    return entry.section in EXTRA_SECTIONS, -entry.importance


def _item_line(n: int, item: Item, notes: bool = False) -> str:
    """notes — показать список изменений релиза целиком (запрос фишек): новые команды и настройки стоят в нём
    дальше первых 400 знаков, и за месяц из релизов Claude Code вышла одна фишка из 58. Тело хранится только
    у источников с body_from_feed; посты сообщества (тоже с телом) остаются обрезанными — их сотня на запрос."""
    reach = coverage(item)
    score = "".join([
        f" источников={reach}" if reach > 1 else "",
        f" HN={item.hn_points}/{item.hn_comments}" if item.hn_points else "",
        f" score={item.score}" if item.score is not None and not item.hn_points else "",
    ])
    text = item.body if notes and item.category == "release" and item.body else item.summary[:400]
    summary = f"\n    {text}" if text else ""
    return f"[{n}] ({item.source}, {item.category}{score}) {item.title}{summary}"


def _story_lines(stories: list[dict] | None) -> str:
    return "\n".join(f"[{s['id']}] {s['name']} — {s['last_date']}: {s['last_title']} (дней: {s['days']})"
                     for s in stories or []) or "(нет)"


def build_prompt(items: list[Item], audience: str, preferences: str = "", stories: list[dict] | None = None) -> str:
    lines = [_item_line(n, item) for n, item in enumerate(items)]
    return PROMPT.format(audience=audience, preferences=preferences or "Оценок читателя пока нет.",
                         stories=_story_lines(stories), items="\n".join(lines))


def _merge(ids: list[int], items: list[Item], used: set[int]) -> Item:
    """Склеивает записи одного события в основную; ids — уже проверенные и ещё не занятые номера."""
    used.update(ids)
    # Модель ставит первым «самое авторитетное издание», а это часто Bloomberg или FT за пейволом, а издание
    # из Google News не открывается без JS. Сортировка устойчивая — среди равных ссылок порядок модели сохраняется
    ids.sort(key=lambda i: link_rank(items[i].url))
    primary = items[ids[0]]
    for extra in ids[1:]:
        absorb(primary, items[extra])
    return primary


def parse_selection(raw: dict, items: list[Item]) -> Digest:
    used: set[int] = set()
    entries = []
    for row in raw.get("items", []):
        ids = [i for i in row.get("ids", []) if 0 <= i < len(items) and i not in used]
        if not ids:
            log.warning("модель вернула событие без валидных ids: %s", row.get("title"))
            continue
        primary = _merge(ids, items, used)
        section = row["section"] if row.get("section") in SECTIONS else FALLBACK_SECTION
        entry = Entry(primary, section, float(row.get("importance", 0)), row["title"], row["summary"], row.get("why", ""))
        entry.story, entry.story_name = row.get("story", ""), row.get("story_name", "")
        entry.status = row["status"] if row.get("status") in STATUSES else ""
        entries.append(entry)
    entries.sort(key=entry_rank)
    noise = [item for n, item in enumerate(items) if n not in used]
    return Digest(raw.get("headline", ""), raw.get("lead", ""), entries, noise)


def _free(digest: Digest, items: list[Item]) -> set[int]:
    """Номера записей, которые первый вызов оставил в шуме. По объекту, а не по равенству: _merge дописывает в
    основную запись склеенные, и равные по полям записи всё равно разные."""
    noise = {id(item) for item in digest.noise}
    return {n for n, item in enumerate(items) if id(item) in noise}


def build_extras_prompt(digest: Digest, items: list[Item], audience: str, stories: list[dict] | None = None) -> str:
    free = _free(digest, items)
    chosen = []
    for entry in digest.entries:
        merged = set(entry.item.also)
        own = [n for n, item in enumerate(items)
               if n not in free and (item is entry.item or (item.source, item.url) in merged)]
        # Заголовков записей хватает, чтобы узнать событие; их описания удвоили бы этот блок
        chosen.append(f"- {entry.title}. {entry.summary}\n"
                      + "\n".join(f"    [{n}] ({items[n].source}) {items[n].title}" for n in own))
    lines = [_item_line(n, item, notes=True) for n, item in enumerate(items) if n in free]
    return EXTRAS_PROMPT.format(audience=audience, chosen="\n".join(chosen) or "(нет)", stories=_story_lines(stories),
                                items="\n".join(lines))


def attach_extras(digest: Digest, raw: dict, items: list[Item]) -> None:
    """Лайфхаки — карточками после событий, «Ещё за день» — строками. Строка, задевшая запись выпуска, — то же
    событие ещё раз: читателю она ничего не добавит. Лайфхаки разбираются первыми — карточка полезнее строки."""
    used = set(range(len(items))) - _free(digest, items)

    def valid(row: dict, kind: str) -> list[int] | None:
        ids = list(dict.fromkeys(i for i in row.get("ids", []) if 0 <= i < len(items)))
        if not ids or not row.get("title") or used.intersection(ids):
            log.warning("%s пропущен — повтор или без валидных ids: %s", kind, row.get("title"))
            return None
        return ids

    for row in raw.get("tips", []):
        if ids := valid(row, "фишка"):
            entry = Entry(_merge(ids, items, used), "tips", float(row.get("importance", 0)), row["title"],
                          row.get("summary", ""), row.get("why", ""))
            # Пока только предложение модели: на страницу попадёт после verify_copies, когда скачан первоисточник
            entry.copy = row.get("copy", "").strip()
            entry.topic = row["topic"] if row.get("topic") in TIP_TOPICS else ""
            digest.entries.append(entry)
    for row in raw.get("more", []):
        if CORPORATE_MONEY.search(row.get("title", "")):
            log.info("строка про корпоративные деньги отброшена: %s", row["title"])
            continue
        if ids := valid(row, "строка «Ещё за день»"):
            digest.more.append(Mention(_merge(ids, items, used), row["title"]))
    digest.entries.sort(key=entry_rank)
    digest.noise = [item for n, item in enumerate(items) if n not in used]


# Команды показываются с кнопкой «Скопировать», поэтому берём их только с сайтов, которые выбрали сами (sources.toml):
# официальные блоги, релизы на GitHub, авторы — и только со страниц на сайте самой ленты. Страницы, куда ведут HN, Reddit,
# новостные ленты или ссылка внутри доверенной ленты, — любой сайт в интернете. Редирект с доверенного сайта считаем его
# собственным выбором: это та же граница доверия, что и для его текста
TRUSTED_COMMAND_CATEGORIES = {"lab", "release", "engineer", "newsletter"}


def _commands_trusted(item: Item) -> bool:
    return item.category in TRUSTED_COMMAND_CATEGORIES and bool(item.feed_host) and bare_host(item.url) == item.feed_host


def _squash(text: str) -> str:
    return " ".join(text.split())


# Промпт из сообщества показываем, только если он похож на обычную фразу для модели: одна строка из букв, пробелов
# и пунктуации — без цифр (IP, порты), путей, спецсимволов оболочки, имён файлов и доменов, без слов про команды,
# сеть, файлы, секреты и отключение защиты. Это эвристика, а не гарантия: вредную просьбу можно сказать и обычными
# словами (три ревью Codex 23.10 находили обходы). Главная защита — пометка «прочитай перед вставкой»; ложные
# отказы (промпт с CLAUDE.md или «files») — цена осторожности
UNTRUSTED_PROMPT_MAX = 300
SAFE_PROMPT_CHARS = re.compile(r"[A-Za-zА-Яа-яЁё ,.!?:;'\"()«»—–-]+")
UNSAFE_SHAPE = re.compile(r"\b\S+\.[A-Za-zА-Яа-я]{2,}\b|\.\w|\b[A-Za-z]:\w|\bdot\s+[a-z]{2,}\b", re.I)
UNSAFE_WORDS = re.compile(
    r"\b(sh|bash|zsh|cmd|ls|pwd|whoami|cd|cat|rm|mv|cp|chmod|chown|sudo|su|curl|wget|nc|ssh|scp|git|pip|npm|npx|uv|"
    r"node|python|docker|env|key|keys|post|http|https|localhost|eval|exec|shell|terminal|console|script|scripts|ip)\b|"
    r"\b(fetch|download|upload|send|forward|paste|request|webhook|invok|execut|instal|delet|remov|wipe|eras|disabl|"
    r"bypass|skip|ignor|disregard|overrid|turn off|switch off|permission|sandbox|safety|safeguard|guardrail|restrict|"
    r"credential|secret|token|password|passwd|cookie|bearer|auth|login|base64|netrc|connect|port|server|host|address|"
    r"file|folder|director|path|disk|drive|readme|repositor|clone)\w*|"
    r"парол|секрет|токен|ключ|отправ|загруз|скача|удал|запуст|выполн|игнорир|отключ|обойд|файл|папк|сервер|адрес|порт",
    re.I)


def _harmless_prompt(text: str) -> bool:
    return (len(text) <= UNTRUSTED_PROMPT_MAX and bool(SAFE_PROMPT_CHARS.fullmatch(text))
            and not UNSAFE_SHAPE.search(text) and not UNSAFE_WORDS.search(text))


def verify_copies(entries: list[Entry], texts: dict[str, str]) -> None:
    """«Скопировать» у фишки — та же граница доверия, что у команд разборов: вставленный агенту чужой промпт
    исполняется, как команда. Сверяем со скачанной страницей первоисточника, а не с описанием из ленты: склейка дублей
    (dedup.absorb) дописывает пустое описание доверенной записи текстом недоверенного дубля, а склейка событий ставит
    первым доверенный релиз рядом с постом с Reddit.
    Исключение по решению владельца (23.10): короткий безобидный промпт из сообщества (не команда) показывается
    с пометкой copy_untrusted — без него фишка с Reddit ссылалась на «эту фразу», которой нигде не было."""
    for entry in entries:
        if not entry.copy:
            continue
        item = entry.item
        verbatim = _squash(entry.copy) in _squash(texts.get(item.url, ""))
        if _commands_trusted(item) and verbatim:
            continue
        if item.category == "community" and verbatim and _harmless_prompt(entry.copy):
            entry.copy_untrusted = True
            continue
        log.warning("«Скопировать» не из текста первоисточника или похоже на команду и атаку — отброшено: %s", item.url)
        entry.copy = ""


def attach_explanations(entries: list[Entry], raw: dict, texts: dict[str, str]) -> None:
    for row in raw.get("items", []):
        n = row.get("id")
        if not isinstance(n, int) or not 0 <= n < len(entries):
            log.warning("разбор с неизвестным id %r пропущен", n)
            continue
        # Дословность отсекает выдумку модели, но не доказывает безопасность: вредоносная страница сама содержит
        # «curl … | sh». Поэтому сверяем только с текстами доверенных источников, у остальных команд не бывает
        item = entries[n].item
        source = _squash(texts.get(item.url, "")) if _commands_trusted(item) else ""
        commands = [c.strip().removeprefix("$").strip() for c in row.get("commands", [])]
        verbatim = [c for c in commands if c and _squash(c) in source]
        if len(verbatim) < len([c for c in commands if c]):
            log.warning("команды не из текста доверенного первоисточника отброшены: %s", item.url)
        entries[n].details = Details(row["what"], list(row.get("points", [])), row.get("try_it", ""),
                                     row.get("caveats", ""), verbatim, _card_terms(entries[n], row.get("terms")))


def _card_terms(entry: Entry, rows: object) -> list[tuple[str, str]]:
    """Не больше двух терминов, и только тех, что читатель встретит в карточке: объяснять невидимое — шум.
    generate схему не проверяет: кривые термины отбрасываются молча, а не роняют выпуск вместе с разбором."""
    if entry.section != "security" or not isinstance(rows, list):
        return []
    card = f"{entry.title} {entry.summary} {entry.why}".casefold()
    terms: list[tuple[str, str]] = []
    for row in rows:
        if not (isinstance(row, dict) and isinstance(row.get("term"), str) and isinstance(row.get("meaning"), str)):
            continue
        term, meaning = row["term"].strip(), row["meaning"].strip()
        key = term.casefold()
        # Термин — в начальной форме, в карточке — в падеже («RCE-уязвимость» / «RCE-уязвимости»): окончание не сверяем
        seen = key in card or (len(key) >= 6 and key[:-2] in card)
        if term and meaning and seen and key not in {t.casefold() for t, _ in terms}:
            terms.append((term, meaning))
    return terms[:2]


# Платная модель цепочки (решение владельца 12.11.2026): бесплатный 3.8 Flash отвечал через раз и ждал по 6 минут,
# выпуски писала Lite. Модели Anthropic узнаём по имени: цепочки в sources.toml остаются списком имён
CLAUDE_PREFIX = "claude-"
# Потолок ответа с запасом: разборы 6 событий заняли 14,8 тыс. токенов вместе с размышлениями (срез 06.11), а с
# фишками и голосами событий до 12. Обрыв по длине — это потерянный вызов и выпуск на запасной модели
CLAUDE_MAX_TOKENS = 32000


def _json_schema(node: dict) -> dict:
    """Схема Gemini (типы прописными, propertyOrdering) → обычная JSON Schema с закрытыми объектами: такую требует
    structured outputs у Anthropic. Порядок полей там задаёт порядок properties, а он уже совпадает с propertyOrdering."""
    out: dict = {"type": node["type"].lower()}
    if "enum" in node:
        out["enum"] = node["enum"]
    if "items" in node:
        out["items"] = _json_schema(node["items"])
    if "properties" in node:
        out["properties"] = {name: _json_schema(child) for name, child in node["properties"].items()}
        out["required"] = node.get("required", list(node["properties"]))
        out["additionalProperties"] = False
    return out


def _generate_claude(prompt: str, schema: dict, model: str) -> dict:
    """Одна попытка на модели Anthropic, с теми же правилами, что у Gemini: любой сбой — LlmError, и цепочка идёт
    дальше. Ключ свой (ANTHROPIC_API_KEY); без него или без денег на счету выпуск выходит на бесплатной цепочке."""
    start = time.monotonic()
    started = datetime.now(timezone.utc)

    def failed(status: int, reason: str) -> LlmError:
        health.record_call(model, "", status, time.monotonic() - start, 0, reason, started)
        return LlmError(f"Claude {model} недоступен через {time.monotonic() - start:.0f} с: {reason}", status)

    key = os.environ.get("ANTHROPIC_API_KEY", "")
    if not key:
        raise failed(0, "NoApiKey")
    # max_retries=0: клиент по умолчанию сам повторяет 429 и 5xx, а у нас повтор — дело цепочки
    client = anthropic.Anthropic(api_key=key, timeout=TIMEOUT, max_retries=0)
    try:
        # Потоком: длинный ответ без потока упирается в таймауты HTTP; нужен только итог
        with client.messages.stream(
                model=model, max_tokens=CLAUDE_MAX_TOKENS, messages=[{"role": "user", "content": prompt}],
                output_config={"format": {"type": "json_schema", "schema": _json_schema(schema)}}) as stream:
            message = stream.get_final_message()
    except anthropic.APIStatusError as exc:
        # Текст ошибки в журнал не пишем целиком: в нём бывает кусок запроса; кода и типа хватает
        raise failed(exc.status_code, type(exc).__name__) from exc
    except anthropic.APIConnectionError as exc:
        raise failed(0, type(exc).__name__) from exc
    elapsed = time.monotonic() - start
    if message.stop_reason != "end_turn":
        # refusal — модель отказалась (новости об эксплойтах), max_tokens — ответ оборван: оба не ответ
        raise failed(200, f"stop:{message.stop_reason}")
    try:
        raw = json.loads(next(block.text for block in message.content if block.type == "text"))
    except (StopIteration, ValueError) as exc:
        raise failed(200, health.BROKEN_ANSWER) from exc
    health.record_call(model, message.model, 200, elapsed, 0, started=started)
    # Свыше 100 тыс. токенов запроса у Haiku 5.5 цена впятеро выше — размер входа должен быть виден в логе
    log.info("Claude %s: вход %s, выход %s, %.0f с", message.model, message.usage.input_tokens,
             message.usage.output_tokens, elapsed)
    return raw


def generate(prompt: str, schema: dict, model: str, api_key: str) -> dict:
    """Одна попытка на одной модели. Повтор на той же модели — ещё один запрос из дневной квоты, поэтому при сбое
    вызывающий переходит к следующей модели (generate_first), а не повторяет."""
    if model.startswith(CLAUDE_PREFIX):
        return _generate_claude(prompt, schema, model)
    body = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"responseMimeType": "application/json", "responseSchema": schema, "temperature": 0.3},
    }
    start = time.monotonic()
    started = datetime.now(timezone.utc)
    try:
        response = httpx.post(API_URL.format(model=model), headers={"x-goog-api-key": api_key}, json=body,
                              timeout=TIMEOUT)
    except httpx.HTTPError as exc:
        health.record_call(model, "", 0, time.monotonic() - start, 0, type(exc).__name__, started)
        raise LlmError(f"Gemini {model} недоступен через {time.monotonic() - start:.0f} с: {type(exc).__name__}") from exc
    # Время ответа отличает сброс нагрузки (503 за секунду) от очереди бесплатного тарифа (минуты)
    elapsed = time.monotonic() - start
    if response.status_code != 200:
        health.record_call(model, "", response.status_code, elapsed, 0, started=started)
        raise LlmError(f"Gemini {model} ответил {response.status_code} через {elapsed:.0f} с: {response.text[:300]}",
                       response.status_code)
    try:
        payload = response.json()
        raw = json.loads(payload["candidates"][0]["content"]["parts"][0]["text"])
    except (KeyError, IndexError, TypeError, ValueError) as exc:
        # ValueError — и битое тело ответа, и битый JSON внутри: оба должны вести к следующей модели цепочки
        health.record_call(model, "", response.status_code, elapsed, 0, health.BROKEN_ANSWER, started)
        raise LlmError(f"не удалось разобрать ответ Gemini {model}: {response.text[:300]}") from exc
    usage = payload.get("usageMetadata", {})
    health.record_call(model, payload.get("modelVersion", model), 200, elapsed, usage.get("thoughtsTokenCount", 0),
                       started=started)
    log.info("Gemini %s: токенов %s, размышления %s, %.0f с", payload.get("modelVersion", model),
             usage.get("totalTokenCount"), usage.get("thoughtsTokenCount", 0), elapsed)
    return raw


def generate_first(prompt: str, schema: dict, models: list[str], api_key: str, call: str = "") -> dict:
    """Ответ первой модели цепочки, которая справилась. Квоты у моделей раздельные: исчерпанный лимит, перегрузка
    или отключённая модель (404) одной не мешают следующей. Повторов на той же модели нет: 503 бесплатного тарифа
    держится часами (панель здоровья 22.10–05.11: повтор отбора через 60 с спас 2 выпуска из ~15, а стоил минуты
    и запроса квоты каждый раз). call — имя вызова для панели здоровья (select, extras…)."""
    since = len(health.RUN.calls)
    try:
        return _first(prompt, schema, models, api_key)
    finally:
        health.label_calls(since, call)


def _first(prompt: str, schema: dict, models: list[str], api_key: str) -> dict:
    error = LlmError("цепочка моделей пуста")
    # Одна и та же модель дважды (model = extras_model в настройках) — это повтор, а он съедает запрос квоты
    for model in dict.fromkeys(models):
        try:
            return generate(prompt, schema, model, api_key)
        except LlmError as exc:
            error = exc
        log.warning("%s — перехожу к следующей модели", error)
    raise error


def select(items: list[Item], audience: str, models: list[str], api_key: str,
           preferences: str = "", stories: list[dict] | None = None) -> Digest:
    prompt = build_prompt(items, audience, preferences, stories)
    return parse_selection(generate_first(prompt, SCHEMA, models, api_key, call="select"), items)


def extras(digest: Digest, items: list[Item], audience: str, models: list[str], api_key: str,
           stories: list[dict] | None = None) -> None:
    """Второй вызов: «Ещё за день» и фишки по записям, которые не вошли в события выпуска. Фишки пишет любая модель
    цепочки, включая Lite: запрет 22.10 (Lite находила 0–1 слабую) снят 06.11 — на срезе с лентой reddit_tips Lite даёт
    2–3 фишки за прогон, в 5 из 7 с дословной командой из источника, а с запретом фишек не было в 11 вечерних выпусках
    из 17. Слабые формулировки summary Lite компенсирует разбор: шаги и команды берутся из текста."""
    prompt = build_extras_prompt(digest, items, audience, stories)
    attach_extras(digest, generate_first(prompt, EXTRAS_SCHEMA, models, api_key, call="extras"), items)


def explain(entries: list[Entry], texts: dict[str, str], audience: str, models: list[str], api_key: str) -> None:
    events = []
    for n, entry in enumerate(entries):
        source = texts.get(entry.item.url, "") or "(текст недоступен)"
        # Текст статьи в кавычках-ограничителях: граница данных видна, даже если статья сама содержит заголовки
        events.append(f"--- событие id={n} · раздел {entry.section} ---\nКарточка: {entry.title}. {entry.summary}\n"
                      f"Описание из ленты: {entry.item.summary[:600]}\nТекст первоисточника:\n{fence(source)}")
    raw = generate_first(EXPLAIN_PROMPT.format(audience=audience, events="\n\n".join(events)), EXPLAIN_SCHEMA, models,
                         api_key, call="explain")
    attach_explanations(entries, raw, texts)
