def entry_rank(entry: Entry) -> tuple[bool, float]:
    """Порядок записей выпуска: авторский пост и лайфхак — не новость дня и идут после событий,
    иначе мнение или приём стали бы «Главным»."""
    return entry.section in EXTRA_SECTIONS, -entry.importance


def _item_line(n: int, item: Item) -> str:
    reach = coverage(item)
    score = "".join([
        f" источников={reach}" if reach > 1 else "",
        f" HN={item.hn_points}/{item.hn_comments}" if item.hn_points else "",
        f" score={item.score}" if item.score is not None and not item.hn_points else "",
    ])
    summary = f"\n    {item.summary[:400]}" if item.summary else ""
    return f"[{n}] ({item.source}, {item.category}{score}) {item.title}{summary}"


def _story_lines(stories: list[dict] | None) -> str:
    return "\n".join(f"[{s['id']}] {s['name']} — {s['last_date']}: {s['last_title']} (дней: {s['days']})"
                     for s in stories or []) or "(нет)"


def build_prompt(items: list[Item], audience: str, preferences: str = "", stories: list[dict] | None = None) -> str:
    lines = [_item_line(n, item) for n, item in enumerate(items)]
    return PROMPT.format(audience=audience, preferences=preferences or "Оценок читателя пока нет.",
                         stories=_story_lines(stories), items="\n".join(lines))


def _merge(ids: list[int], items: list[Item], used: set[int]) -> Item:
    """Склеивает записи одного события в основную; ids — уже проверенные и ещё не занятые номера."""
    used.update(ids)
    # Модель ставит первым «самое авторитетное издание», а это часто Bloomberg или FT за пейволом, а издание
    # из Google News не открывается без JS. Сортировка устойчивая — среди равных ссылок порядок модели сохраняется
    ids.sort(key=lambda i: link_rank(items[i].url))
    primary = items[ids[0]]
    for extra in ids[1:]:
        absorb(primary, items[extra])
    return primary


def parse_selection(raw: dict, items: list[Item]) -> Digest:
    used: set[int] = set()
    entries = []
    for row in raw.get("items", []):
        ids = [i for i in row.get("ids", []) if 0 <= i < len(items) and i not in used]
        if not ids:
            log.warning("модель вернула событие без валидных ids: %s", row.get("title"))
            continue
        primary = _merge(ids, items, used)
        section = row["section"] if row.get("section") in SECTIONS else FALLBACK_SECTION
        entry = Entry(primary, section, float(row.get("importance", 0)), row["title"], row["summary"], row.get("why", ""))
        entry.story, entry.story_name = row.get("story", ""), row.get("story_name", "")
        entry.status = row["status"] if row.get("status") in STATUSES else ""
        entries.append(entry)
    entries.sort(key=entry_rank)
    noise = [item for n, item in enumerate(items) if n not in used]
    return Digest(raw.get("headline", ""), raw.get("lead", ""), entries, noise)


def _free(digest: Digest, items: list[Item]) -> set[int]:
    """Номера записей, которые первый вызов оставил в шуме. По объекту, а не по равенству: _merge дописывает в
    основную запись склеенные, и равные по полям записи всё равно разные."""
    noise = {id(item) for item in digest.noise}
    return {n for n, item in enumerate(items) if id(item) in noise}


def build_extras_prompt(digest: Digest, items: list[Item], audience: str, stories: list[dict] | None = None) -> str:
    free = _free(digest, items)
    chosen = []
    for entry in digest.entries:
        merged = set(entry.item.also)
        own = [n for n, item in enumerate(items)
               if n not in free and (item is entry.item or (item.source, item.url) in merged)]
        # Заголовков записей хватает, чтобы узнать событие; их описания удвоили бы этот блок
        chosen.append(f"- {entry.title}. {entry.summary}\n"
                      + "\n".join(f"    [{n}] ({items[n].source}) {items[n].title}" for n in own))
    lines = [_item_line(n, item) for n, item in enumerate(items) if n in free]
    return EXTRAS_PROMPT.format(audience=audience, chosen="\n".join(chosen) or "(нет)", stories=_story_lines(stories),
                                items="\n".join(lines))


def attach_extras(digest: Digest, raw: dict, items: list[Item]) -> None:
    """Лайфхаки — карточками после событий, «Ещё за день» — строками. Строка, задевшая запись выпуска, — то же
    событие ещё раз: читателю она ничего не добавит. Лайфхаки разбираются первыми — карточка полезнее строки."""
    used = set(range(len(items))) - _free(digest, items)

    def valid(row: dict, kind: str) -> list[int] | None:
        ids = list(dict.fromkeys(i for i in row.get("ids", []) if 0 <= i < len(items)))
        if not ids or not row.get("title") or used.intersection(ids):
            log.warning("%s пропущен — повтор или без валидных ids: %s", kind, row.get("title"))
            return None
        return ids

    for row in raw.get("tips", []):
        if ids := valid(row, "фишка"):
            entry = Entry(_merge(ids, items, used), "tips", float(row.get("importance", 0)), row["title"],
                          row.get("summary", ""), row.get("why", ""))
            # Пока только предложение модели: на страницу попадёт после verify_copies, когда скачан первоисточник
            entry.copy = row.get("copy", "").strip()
            digest.entries.append(entry)
    for row in raw.get("more", []):
        if CORPORATE_MONEY.search(row.get("title", "")):
            log.info("строка про корпоративные деньги отброшена: %s", row["title"])
            continue
        if ids := valid(row, "строка «Ещё за день»"):
            digest.more.append(Mention(_merge(ids, items, used), row["title"]))
    digest.entries.sort(key=entry_rank)
    digest.noise = [item for n, item in enumerate(items) if n not in used]


# Команды показываются с кнопкой «Скопировать», поэтому берём их только с сайтов, которые выбрали сами (sources.toml):
# официальные блоги, релизы на GitHub, авторы — и только со страниц на сайте самой ленты. Страницы, куда ведут HN, Reddit,
# новостные ленты или ссылка внутри доверенной ленты, — любой сайт в интернете. Редирект с доверенного сайта считаем его
# собственным выбором: это та же граница доверия, что и для его текста
TRUSTED_COMMAND_CATEGORIES = {"lab", "release", "engineer", "newsletter"}


def _commands_trusted(item: Item) -> bool:
    return item.category in TRUSTED_COMMAND_CATEGORIES and bool(item.feed_host) and bare_host(item.url) == item.feed_host


def _squash(text: str) -> str:
    return " ".join(text.split())


def verify_copies(entries: list[Entry], texts: dict[str, str]) -> None:
    """«Скопировать» у фишки — та же граница доверия, что у команд разборов: вставленный агенту чужой промпт
    исполняется, как команда. Сверяем со скачанной страницей первоисточника, а не с описанием из ленты: склейка дублей
    (dedup.absorb) дописывает пустое описание доверенной записи текстом недоверенного дубля, а склейка событий ставит
    первым доверенный релиз рядом с постом с Reddit."""
    for entry in entries:
        if not entry.copy:
            continue
        item = entry.item
        if not (_commands_trusted(item) and _squash(entry.copy) in _squash(texts.get(item.url, ""))):
            log.warning("«Скопировать» не из текста доверенного первоисточника отброшено: %s", item.url)
            entry.copy = ""


def attach_explanations(entries: list[Entry], raw: dict, texts: dict[str, str]) -> None:
    for row in raw.get("items", []):
        n = row.get("id")
        if not isinstance(n, int) or not 0 <= n < len(entries):
            log.warning("разбор с неизвестным id %r пропущен", n)
            continue
        # Дословность отсекает выдумку модели, но не доказывает безопасность: вредоносная страница сама содержит
        # «curl … | sh». Поэтому сверяем только с текстами доверенных источников, у остальных команд не бывает
        item = entries[n].item
        source = _squash(texts.get(item.url, "")) if _commands_trusted(item) else ""
        commands = [c.strip().removeprefix("$").strip() for c in row.get("commands", [])]
        verbatim = [c for c in commands if c and _squash(c) in source]
        if len(verbatim) < len([c for c in commands if c]):
            log.warning("команды не из текста доверенного первоисточника отброшены: %s", item.url)
        entries[n].details = Details(row["what"], list(row.get("points", [])), row.get("try_it", ""),
                                     row.get("caveats", ""), verbatim)


def generate(prompt: str, schema: dict, model: str, api_key: str) -> dict:
    """Одна попытка на одной модели. Повтор на той же модели — ещё один запрос из дневной квоты, поэтому при сбое
    вызывающий переходит к следующей модели (generate_first), а не повторяет."""
    body = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"responseMimeType": "application/json", "responseSchema": schema, "temperature": 0.3},
    }
    start = time.monotonic()
    try:
        response = httpx.post(API_URL.format(model=model), headers={"x-goog-api-key": api_key}, json=body,
                              timeout=TIMEOUT)
    except httpx.HTTPError as exc:
        raise LlmError(f"Gemini {model} недоступен через {time.monotonic() - start:.0f} с: {type(exc).__name__}") from exc
    # Время ответа отличает сброс нагрузки (503 за секунду) от очереди бесплатного тарифа (минуты)
    elapsed = time.monotonic() - start
    if response.status_code != 200:
        raise LlmError(f"Gemini {model} ответил {response.status_code} через {elapsed:.0f} с: {response.text[:300]}",
                       response.status_code)
    try:
        payload = response.json()
        raw = json.loads(payload["candidates"][0]["content"]["parts"][0]["text"])
    except (KeyError, IndexError, TypeError, ValueError) as exc:
        # ValueError — и битое тело ответа, и битый JSON внутри: оба должны вести к следующей модели цепочки
        raise LlmError(f"не удалось разобрать ответ Gemini {model}: {response.text[:300]}") from exc
    usage = payload.get("usageMetadata", {})
    log.info("Gemini %s: токенов %s, размышления %s, %.0f с", payload.get("modelVersion", model),
             usage.get("totalTokenCount"), usage.get("thoughtsTokenCount", 0), elapsed)
    return raw


def generate_first(prompt: str, schema: dict, models: list[str], api_key: str, overload_wait: float = 0) -> dict:
    """Ответ первой модели цепочки, которая справилась. Квоты у моделей раздельные: исчерпанный лимит, перегрузка
    или отключённая модель (404) одной не мешают следующей. overload_wait > 0 — один повтор первой модели после 503."""
    error = LlmError("цепочка моделей пуста")
    # Одна и та же модель дважды (model = extras_model в настройках) — это повтор, а он съедает запрос квоты
    for n, model in enumerate(dict.fromkeys(models)):
        try:
            return generate(prompt, schema, model, api_key)
        except LlmError as exc:
            error = exc
        if n == 0 and overload_wait and error.status == 503:
            log.warning("%s — повтор через %.0f с", error, overload_wait)
            time.sleep(overload_wait)
            try:
                return generate(prompt, schema, model, api_key)
            except LlmError as exc:
                error = exc
        log.warning("%s — перехожу к следующей модели", error)
    raise error


def select(items: list[Item], audience: str, models: list[str], api_key: str,
           preferences: str = "", stories: list[dict] | None = None) -> Digest:
    prompt = build_prompt(items, audience, preferences, stories)
    # Отбор решает качество выпуска: один повтор лучшей модели после перегрузки стоит запроса квоты
    return parse_selection(generate_first(prompt, SCHEMA, models, api_key, overload_wait=OVERLOAD_WAIT), items)


def extras(digest: Digest, items: list[Item], audience: str, models: list[str], api_key: str,
           stories: list[dict] | None = None) -> None:
    """Второй вызов: «Ещё за день» и фишки по записям, которые не вошли в события выпуска."""
    raw = generate_first(build_extras_prompt(digest, items, audience, stories), EXTRAS_SCHEMA, models, api_key)
    attach_extras(digest, raw, items)


def explain(entries: list[Entry], texts: dict[str, str], audience: str, models: list[str], api_key: str) -> None:
    events = []
    for n, entry in enumerate(entries):
        source = texts.get(entry.item.url, "") or "(текст недоступен)"
        # Текст статьи в кавычках-ограничителях: граница данных видна, даже если статья сама содержит заголовки
        events.append(f"--- событие id={n} ---\nКарточка: {entry.title}. {entry.summary}\n"
                      f"Описание из ленты: {entry.item.summary[:600]}\nТекст первоисточника:\n{fence(source)}")
    raw = generate_first(EXPLAIN_PROMPT.format(audience=audience, events="\n\n".join(events)), EXPLAIN_SCHEMA, models,
                         api_key)
    attach_explanations(entries, raw, texts)
